// Module 6 — Reporting. "Generate report" and "Export" both just
// build text in memory and hand it to the browser as a download —
// there's no report-rendering backend yet. Swap buildReportText() for
// a real PDF service once one exists; the shape of the data won't
// change.

import React, { useState } from 'react'
import { Card, ToggleGroup, downloadTextFile } from './ui.jsx'

function buildReportText(result, docType) {
  return [
    'BYTEMIND VERIFICATION REPORT',
    '='.repeat(32),
    `Verification ID: ${result.id}`,
    `Logged at: ${new Date(result.timestamp).toLocaleString()}`,
    `Document type: ${docType || 'Unknown'}`,
    `Decision: ${result.decision.replace('_', ' ')}`,
    `Trust score: ${result.trustScore}/100`,
    `Risk score: ${result.riskScore}/100`,
    '',
    'OCR',
    `  Confidence: ${result.ocr.confidence}%`,
    `  Full name: ${result.ocr.fields.fullName}`,
    `  Document number: ${result.ocr.fields.documentNumber}`,
    `  Date of birth: ${result.ocr.fields.dateOfBirth}`,
    `  Expiry date: ${result.ocr.fields.expiryDate}`,
    `  Nationality: ${result.ocr.fields.nationality}`,
    '',
    'MRZ',
    `  Valid: ${result.mrz.valid ? 'yes' : 'no'}`,
    `  Checksums: ${result.mrz.checksumsPassed}/${result.mrz.checksumsTotal}`,
    '',
    'Face match',
    `  Score: ${result.faceMatch.score}%`,
    `  Liveness passed: ${result.faceMatch.livenessPassed ? 'yes' : 'no'}`,
    '',
    'Authenticity & tampering',
    `  Authenticity score: ${result.authenticity.score}/100`,
    `  Security features: ${result.authenticity.securityFeaturesDetected.join(', ')}`,
    `  Tampering score: ${result.tampering.score}/100`,
    `  Suspicious regions: ${result.tampering.suspiciousRegions.length}`,
    '',
    'Risk contributors',
    ...result.riskContributors.map((c) => `  ${c.label}: ${c.weight} pts`),
    '',
    `Record hash: ${result.hash}`,
    '',
    'Generated by ByteMind — prototype build, not a production report.',
  ].join('\n')
}

function buildCsv(result) {
  const rows = [
    ['field', 'value'],
    ['verification_id', result.id],
    ['timestamp', result.timestamp],
    ['decision', result.decision],
    ['trust_score', result.trustScore],
    ['risk_score', result.riskScore],
    ['ocr_confidence', result.ocr.confidence],
    ['mrz_valid', result.mrz.valid],
    ['face_match_score', result.faceMatch.score],
    ['authenticity_score', result.authenticity.score],
    ['tampering_score', result.tampering.score],
    ['hash', result.hash],
  ]
  return rows.map((r) => r.map((v) => `"${String(v).replace(/"/g, '""')}"`).join(',')).join('\n')
}

const FORMATS = [
  { value: 'json', label: 'JSON' },
  { value: 'csv', label: 'CSV' },
  { value: 'txt', label: 'TXT' },
]

export default function ReportingTab({ result, docType }) {
  const [format, setFormat] = useState('json')
  const [generated, setGenerated] = useState(false)

  function handleGenerateReport() {
    downloadTextFile(`verification-report-${result.id}.txt`, buildReportText(result, docType))
    setGenerated(true)
  }

  function handleExport() {
    if (format === 'json') {
      downloadTextFile(`verification-${result.id}.json`, JSON.stringify(result, null, 2), 'application/json')
    } else if (format === 'csv') {
      downloadTextFile(`verification-${result.id}.csv`, buildCsv(result), 'text/csv')
    } else {
      downloadTextFile(`verification-${result.id}.txt`, buildReportText(result, docType))
    }
  }

  return (
    <div className="grid grid-cols-1 gap-4 lg:grid-cols-2">
      <Card title="Verification Summary" subtitle="What gets included in the report." className="lg:col-span-2">
        <dl className="grid grid-cols-2 gap-x-6 gap-y-3 text-sm sm:grid-cols-3">
          <SummaryRow label="Verification ID" value={result.id} mono />
          <SummaryRow label="Document type" value={docType || 'Unknown'} />
          <SummaryRow label="Decision" value={result.decision.replace('_', ' ')} className="capitalize" />
          <SummaryRow label="Trust score" value={`${result.trustScore}/100`} />
          <SummaryRow label="Risk score" value={`${result.riskScore}/100`} />
          <SummaryRow label="Logged at" value={new Date(result.timestamp).toLocaleString()} />
        </dl>
      </Card>

      <Card
        title="Generate Report"
        subtitle="A plain-text summary — swap for a rendered PDF once a report service exists."
      >
        <button
          onClick={handleGenerateReport}
          className="w-full rounded-sm bg-signal px-4 py-2.5 text-sm font-medium text-ink transition-colors hover:bg-signal/90"
        >
          Generate &amp; download report
        </button>
        {generated && (
          <p className="mt-3 text-xs text-safe">
            Downloaded as verification-report-{result.id}.txt
          </p>
        )}
      </Card>

      <Card title="Export" subtitle="Raw verification data, for feeding into another system.">
        <ToggleGroup options={FORMATS} value={format} onChange={setFormat} />
        <button
          onClick={handleExport}
          className="mt-4 w-full rounded-sm border border-line2 px-4 py-2.5 text-sm font-medium text-inktext transition-colors hover:border-ink2"
        >
          Export as {format.toUpperCase()}
        </button>
      </Card>
    </div>
  )
}

function SummaryRow({ label, value, mono, className = '' }) {
  return (
    <div>
      <dt className="text-xs text-ink2">{label}</dt>
      <dd className={`mt-0.5 text-sm text-inktext ${mono ? 'font-mono' : ''} ${className}`}>{value}</dd>
    </div>
  )
}
